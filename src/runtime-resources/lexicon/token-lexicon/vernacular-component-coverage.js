function applyVernacularComponentCoverage(entries) {
  const seen = new Set();
  const out = entries.map(([surface, entry]) => {
    seen.add(surface);
    const reading = READINGS[surface];
    if (!reading || String(entry && entry.jyutping || "").trim()) return [surface, entry];
    return [surface, {
      ...entry,
      jyutping: reading,
      note: [entry && entry.note, `Pronunciation filled from ${SOURCE}; external bounded vernacular audit exposed missing component reading.`].filter(Boolean).join(" "),
    }];
  });

  for (const [surface, jyutping] of Object.entries(READINGS)) {
    if (seen.has(surface)) continue;
    out.push([surface, {
      label: "lex",
      pos: "lexical_item",
      syntax: "lexical_item",
      jyutping,
      note: `Neutral component coverage from ${SOURCE}; no grammar/category promotion is implied.`,
      provenance: { kind: "external_vernacular_component_reading", source: SOURCE, url: SOURCE_URL },
    }]);
  }
  return out;
}

module.exports = Object.freeze({ SOURCE, SOURCE_URL, READINGS, applyVernacularComponentCoverage });
